import { createRequire } from 'node:module';

import js from '@eslint/js';
import prettier from 'eslint-config-prettier';
import jsxA11y from 'eslint-plugin-jsx-a11y';
import react from 'eslint-plugin-react';
import reactHooks from 'eslint-plugin-react-hooks';
import reactRefresh from 'eslint-plugin-react-refresh';
import { defineConfig, globalIgnores } from 'eslint/config';
import globals from 'globals';
import tseslint from 'typescript-eslint';

/**
 * Read React's version from the installed package rather than hardcoding it.
 *
 * eslint-plugin-react's own 'detect' setting crashes on eslint 10 with
 * "contextOrFilename.getFilename is not a function" - its detection path calls
 * an API eslint 10 removed. A hardcoded version avoids the crash but goes
 * stale the moment React is upgraded, silently applying the wrong era of rules
 * to react/no-deprecated and friends. Reading package.json gets both.
 */
const reactVersion = createRequire(import.meta.url)(
	'react/package.json',
).version;

export default defineConfig([
	globalIgnores([
		'**/dist',
		'**/node_modules',
		// Regenerated by the shadcn CLI; it exports cva variants alongside
		// components, which react-refresh/only-export-components flags.
		'packages/web/src/components/ui',
		// Written by scripts/sync-steam.mjs.
		'packages/shared/src/generated',
	]),

	// Every package, including shared and api which were previously unlinted.
	{
		files: ['**/*.{ts,tsx}'],
		extends: [js.configs.recommended, tseslint.configs.recommended],
		rules: {
			// Honour the leading-underscore convention, which TypeScript's own
			// noUnusedParameters already does. Without this the two disagree:
			// tsc accepts a deliberately-unused `_init` and eslint rejects it.
			'@typescript-eslint/no-unused-vars': [
				'error',
				{
					argsIgnorePattern: '^_',
					varsIgnorePattern: '^_',
					caughtErrorsIgnorePattern: '^_',
				},
			],
		},
	},

	// The browser half.
	//
	// react-hooks covers hook rules and react-refresh covers fast-refresh
	// safety, but neither looks at JSX itself: a missing list key, an <img>
	// with no alt, a click handler on a non-interactive element and a
	// target="_blank" without rel all passed before these two were added.
	//
	// Both plugins cap their peer range at eslint 9 and we are on 10, so they
	// are installed with --legacy-peer-deps.
	//
	{
		files: ['packages/web/src/**/*.{ts,tsx}'],
		extends: [
			react.configs.flat.recommended,
			react.configs.flat['jsx-runtime'],
			jsxA11y.flatConfigs.recommended,
			reactHooks.configs.flat.recommended,
			reactRefresh.configs.vite,
		],
		languageOptions: { globals: globals.browser },
		settings: { react: { version: reactVersion } },
		rules: {
			// TypeScript checks props; prop-types is redundant noise here.
			'react/prop-types': 'off',
		},
	},

	// Things that run in node: the Lambda handler, the generator, vite config.
	{
		files: [
			'packages/api/src/**/*.ts',
			'packages/web/vite.config.ts',
			'packages/web/build.mjs',
			'packages/api/build.mjs',
			'scripts/**/*.mjs',
			'eslint.config.js',
		],
		languageOptions: { globals: globals.node },
	},

	// Must come last: switches off the rules that would argue with Prettier.
	prettier,
]);
